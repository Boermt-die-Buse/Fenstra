# Grundbausteine


def S(d, w=1.0):
    """Strichpfad"""
    return f'<path d="{d}" fill="none" stroke="currentColor" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'


def F(d):
    """gefüllter Pfad"""
    return f'<path d="{d}" fill="currentColor"/>'


def L(x1, y1, x2, y2, w=1.0):
    return S(f'M{x1} {y1}L{x2} {y2}', w)


def R(x, y, w, h, r=0.0, sw=1.0):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="none" stroke="currentColor" stroke-width="{sw}"/>'


def RF(x, y, w, h, r=0.0):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="currentColor"/>'


def C(cx, cy, r, sw=1.0):
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="currentColor" stroke-width="{sw}"/>'


def D(cx, cy, r):
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="currentColor"/>'


def arc(cx, cy, r, a0, a1):
    """Kreisbogen von Winkel a0 nach a1 (Grad, 0 = rechts, im Uhrzeigersinn wie SVG)."""
    x0 = cx + r * math.cos(math.radians(a0))
    y0 = cy + r * math.sin(math.radians(a0))
    x1 = cx + r * math.cos(math.radians(a1))
    y1 = cy + r * math.sin(math.radians(a1))
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f'M{x0:.2f} {y0:.2f}A{r} {r} 0 {large} 1 {x1:.2f} {y1:.2f}'


def g(name, *parts):
    GLYPHS[name] = ''.join(parts)


