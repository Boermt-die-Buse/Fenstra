def star_path(cx, cy, ro, ri, n=5, rot=-90):
    pts = []
    for i in range(2 * n):
        r = ro if i % 2 == 0 else ri
        a = math.radians(rot + i * 180 / n)
        pts.append(f'{cx + r * math.cos(a):.2f} {cy + r * math.sin(a):.2f}')
    return 'M' + 'L'.join(pts) + 'Z'


def gear_path(cx, cy, ro, ri, teeth=8, tooth=0.42):
    """Zahnrad als Umrisspfad (Zähne mit leicht abgerundeten Flanken)."""
    pts = []
    step = 360 / teeth
    for i in range(teeth):
        a = i * step
        for da, r in ((-step * tooth / 2 - 4, ri), (-step * tooth / 2, ro), (step * tooth / 2, ro), (step * tooth / 2 + 4, ri)):
            ang = math.radians(a + da)
            pts.append(f'{cx + r * math.cos(ang):.2f} {cy + r * math.sin(ang):.2f}')
    return 'M' + 'L'.join(pts) + 'Z'


