BADGE_CX, BADGE_CY, BADGE_R = 12.0, 12.0, 4.0


def badge(base, mark, name_hint='b'):
    mid = f'm-{name_hint}'
    mask = (f'<mask id="{mid}"><rect x="0" y="0" width="16" height="16" fill="#fff"/>'
            f'<circle cx="{BADGE_CX}" cy="{BADGE_CY}" r="{BADGE_R + 1}" fill="#000"/></mask>')
    return f'<defs>{mask}</defs><g mask="url(#{mid})">{GLYPHS[base]}</g>{mark}'


